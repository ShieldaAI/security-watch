// Regenerates src/word-filter.ts: a Bloom filter of English dictionary words.
//
// Source: /usr/share/dict/web2 (Webster's Second International, 1934; the copyright has lapsed)
// and /usr/share/dict/propernames, as shipped with macOS and the BSDs. Entries of 3 to 12 letters
// are used, in lower case. Run on a machine that has the file: `node scripts/build-word-filter.mjs`.
// The output is committed; a build never needs the word list.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const directory = process.argv[2] ?? '/usr/share/dict';
// Capitalised entries and the list of given names are included in lower case: "Jason Miller" and
// "the city of Phoenix" are prose too, and a package named `jason` or `phoenix` is rarely meant.
const words = [
  ...new Set(
    ['web2', 'propernames']
      .flatMap((file) => readFileSync(`${directory}/${file}`, 'utf8').split('\n'))
      .map((word) => word.toLowerCase())
      .filter((word) => /^[a-z]{3,12}$/.test(word)),
  ),
].sort();
const BITS_PER_WORD = 10;
const HASHES = 7;
const bits = Math.ceil((words.length * BITS_PER_WORD) / 8) * 8;
const filter = new Uint8Array(bits / 8);
/** FNV-1a over the characters, from two different starting values: the two halves of a double hash. */
function hashes(word) {
  let first = 0x811c9dc5;
  let second = 0x01000193;
  for (let index = 0; index < word.length; index++) {
    const code = word.charCodeAt(index);
    first = Math.imul(first ^ code, 0x01000193) >>> 0;
    second = Math.imul(second ^ code, 0x5bd1e995) >>> 0;
  }
  return [first, second | 1];
}
for (const word of words) {
  const [first, second] = hashes(word);
  for (let round = 0; round < HASHES; round++) {
    const bit = (first + Math.imul(round, second)) >>> 0;
    const position = bit % bits;
    filter[position >> 3] |= 1 << (position & 7);
  }
}
const data = Buffer.from(filter).toString('base64');
const lines = data.match(/.{1,100}/g).join('\n');
writeFileSync(
  fileURLToPath(new URL('../src/word-filter.ts', import.meta.url)),
  `// Generated by scripts/build-word-filter.mjs; do not edit by hand.
// A Bloom filter of ${words.length} English dictionary words and given names of 3 to 12 letters, in lower
// case, taken from Webster's Second International (1934, copyright lapsed) and the BSD name list. A word in the dictionary is always found;
// about one word in a hundred that is not in it is found as well.
export const WORD_FILTER_BITS = ${bits};
export const WORD_FILTER_HASHES = ${HASHES};
// Typed as a plain string so that the declaration file does not repeat the data.
export const WORD_FILTER_DATA: string = \`
${lines}
\`;
`,
);
console.log(`${words.length} words, ${bits / 8} bytes, ${data.length} characters of base64`);
